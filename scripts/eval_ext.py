#!/usr/bin/env python3
"""Score the shipped system against an *external* Phase 2 dataset.

Why this exists separately from `eval_phase2.py`: that script scores a split
produced by our own generator, so it shares every modelling assumption with the
thing under test. A number measured that way cannot see a domain gap. This
script runs the same rubric against a dataset generated by someone else's
generator, which is the closest available proxy for the blind set.

Two honesty rules are enforced here and are the reason the numbers differ from
`eval_phase2.py`:

* **Rejection F1 is reported at the *shipped fixed* threshold**, the one
  `register.py` will actually use on the blind set. The best-achievable F1 over
  a swept threshold is also printed, but clearly labelled, because choosing the
  threshold after seeing the labels is not a result.
* **Localisation is combined with the published weights** (0.45*A + 0.55*B),
  not pooled, so the degraded set carries the weight the rubric gives it.

Inference is parallel across processes purely for wall-clock; per-pair timings
collected here are therefore NOT valid for the efficiency component. Measure
that separately, single-process at 4 threads, on an idle machine.
"""
from __future__ import annotations

import argparse
import os
import sys
import time

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, HERE)

# The shipped Phase 2 operating point, read from the ONE shared definition
# (driftsense.config) so a default run here decodes and gates exactly what
# register.py ships -- pinned by tests/test_submission_parity.py.
from driftsense.config import SHIPPED_BAND, SHIPPED_THRESHOLD, SHIPPED_VERIFICATION
from driftsense.config import SHIPPED_SUBPIXEL_ROWS, SHIPPED_STRIP_ROTATION

# The rubric -- credit tiers, A/B weighting and the scorer itself -- lives in
# driftsense.rubric so that this script and scripts/eval_phase2.py cannot drift
# apart on submission masking or strata weighting (they had). Re-exported at
# module level because tests/test_eval_found_masking.py and
# tests/test_score_semantics.py load this file by path and read these names.
from driftsense.rubric import (  # noqa: E402,F401
    LOC_TIERS, ROT_TIERS, SCALE_TIERS, W_A, W_B, score, tier)


def _worker(job):
    """Run one pair. Imports happen inside so each process sets its own threads."""
    (shard_dir, row, weights, threads, hypotheses, polish, polish_scale, refit_xy,
     coarse, band, verification, denoise, tie_tol, features,
     early_exit, rescue_margin, rescue_delta, subpixel_rows, strip_rot) = job
    import torch
    torch.set_num_threads(threads)
    import cv2
    # OpenCV otherwise spawns a pool per *process*, so N workers oversubscribe
    # the machine N-fold and every per-pair timing becomes meaningless.
    cv2.setNumThreads(threads)
    import infer as I
    from driftsense.matching import locate_phase2

    global _MODEL
    try:
        model, device = _MODEL
    except NameError:
        _MODEL = I.load_model(weights)
        model, device = _MODEL

    ref = I.read_gray(os.path.join(shard_dir, row["reference_path"]))
    sea = I.read_gray(os.path.join(shard_dir, row["search_path"]))
    t0 = time.perf_counter()
    res = locate_phase2(model, ref, sea, device, refine=True,
                        hypotheses=hypotheses, polish=polish,
                        polish_scale=polish_scale, refit_xy=refit_xy,
                        coarse_scales=coarse, band=band,
                        verification=verification, denoise=denoise,
                        tie_tol=tie_tol, early_exit_zncc=early_exit,
                        rescue_margin=rescue_margin, rescue_delta=rescue_delta,
                        subpixel_rows=subpixel_rows, strip_rot=strip_rot,
                        # --features: compute the rank/band feature maps and the
                        # winner margin WITHOUT changing the selector -- the
                        # hypothesis choice stays the shipped zncc winner, so the
                        # recorded features describe exactly the decode
                        # register.py ships (issue #6).
                        return_hypotheses=features)
    dt = time.perf_counter() - t0
    return {
        "pair_id": row["pair_id"], "set": row["phase2_set"],
        "severity": row.get("severity_level", -1),
        "architecture": row.get("architecture", ""),
        "gt_found": int(row["found"]),
        "gt_x": row["gt_x_corr"], "gt_y": row["gt_y_corr"],
        "gt_scale": row["magnification"], "gt_rot": row["rotation_deg"],
        "x": res["x"], "y": res["y"],
        "scale": res.get("scale", np.nan), "theta": res.get("theta", np.nan),
        # The column register.py actually writes: min(network score, native
        # ZNCC). Recording the raw network score here instead made every
        # threshold in this harness mean something different from the shipped
        # one, which is a very easy way to report a number nobody can reproduce.
        "score": float(res.get("confidence", res.get("score", np.nan))),
        "net_score": float(res.get("score", np.nan)),
        "zncc": float(res.get("zncc", np.nan)),
        # Recorded so the rejection/calibration decision can be re-tuned
        # offline without paying for inference again. peak_ratio is how
        # contested the network's choice was (runner-up / winner among
        # well-separated peaks); pose_peak is the coarse correlation of the
        # winning pose hypothesis.
        "peak_ratio": float(res.get("peak_ratio", np.nan)),
        "pose_peak": float(res.get("pose_peak", np.nan)),
        # Peak-shape statistics (Bolme et al., MOSSE, CVPR 2010). score and
        # zncc are peak *heights* and peak_ratio is a margin over the runner-up;
        # neither describes the surface the peak sits on, and a confident wrong
        # lock-on is a tall peak on a busy surface. Recorded here so a rejector
        # fitted on training shards can be scored on this set without a second
        # inference pass -- without them the fit could never be validated.
        "psr": float(res.get("psr", np.nan)),
        "apce": float(res.get("apce", np.nan)),
        # Rank/band peak-quality at the winner (issue #6): only present when
        # the feature maps are computed (--features, or --verification is not
        # zncc). Recorded so rejector_cv.py can fit the present/absent
        # decision on inference-time features without a second pass.
        "rank": float(res.get("rank", np.nan)),
        "band": float(res.get("band", np.nan)),
        # Winner's min(score, zncc) margin over the runner-up (issue #6);
        # attached by locate_phase2 on every decode path.
        "margin": float(res.get("winner_margin", np.nan)),
        "n_hyp": int(res.get("n_hypotheses", 0)),
        "n_hyp_offered": int(res.get("n_hypotheses_offered", 0)),
        "winner_margin": float(res.get("winner_margin", np.nan)),
        "rescued": int(bool(res.get("rescued", False))),
        "secs": dt,
    }


def sample_pairs(df, n: int, seed: int = 0):
    """A deterministic, replacement-free draw of `n` pairs — the local
    emulation of the organisers' 200-pair blind grade. A sample larger than
    the frame returns the whole frame."""
    if n >= len(df):
        return df
    return df.sample(n=n, random_state=seed)


def run(shards, weights, jobs, threads, limit, hypotheses, polish,
        polish_scale, refit_xy, stride, coarse, band, verification, denoise,
        tie_tol, features=False, sample=0, seed=0, early_exit=None,
        rescue_margin=None, rescue_delta=0.0, subpixel_rows=False,
        strip_rot=False):
    import multiprocessing as mp

    tasks = []
    for d in shards:
        man = pd.read_csv(os.path.join(d, "manifest.csv"))
        if stride > 1:
            man = man.iloc[::stride]
        if limit:
            man = man.head(limit)
        for _, r in man.iterrows():
            tasks.append((d, r.to_dict(), weights, threads, hypotheses, polish,
                          polish_scale, refit_xy, coarse, band, verification,
                          denoise, tie_tol, features,
                          early_exit, rescue_margin, rescue_delta,
                          subpixel_rows, strip_rot))
    print(f"{len(tasks)} pairs over {len(shards)} shard(s), {jobs} workers", flush=True)
    if sample:
        rng = np.random.RandomState(seed)
        idx = rng.choice(len(tasks), size=min(sample, len(tasks)), replace=False)
        tasks = [tasks[i] for i in sorted(idx)]
        print(f"  sampled {len(tasks)} pairs (seed {seed}) for the 200-pair grade emulation", flush=True)

    out, t0 = [], time.perf_counter()
    with mp.Pool(jobs) as pool:
        for i, r in enumerate(pool.imap_unordered(_worker, tasks, chunksize=4), 1):
            out.append(r)
            if i % 100 == 0:
                el = time.perf_counter() - t0
                print(f"  {i}/{len(tasks)}  {el/i:.2f}s/pair wall  eta {(len(tasks)-i)*el/i/60:.1f} min",
                      flush=True)
    return pd.DataFrame(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("shards", nargs="+")
    ap.add_argument("--weights", default=os.path.join(HERE, "weights", "driftsense.pt"))
    ap.add_argument("--out", default=None, help="write per-pair results CSV")
    ap.add_argument("--rescore", default=None, help="skip inference, score this CSV")
    ap.add_argument("--jobs", type=int, default=6)
    ap.add_argument("--threads", type=int, default=4)
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--hypotheses", type=int, default=3)
    ap.add_argument("--no-polish", action="store_true")
    ap.add_argument("--no-polish-scale", action="store_true")
    ap.add_argument("--refit-xy", action="store_true")
    ap.add_argument("--subpixel-rows", action="store_true",
                    default=SHIPPED_SUBPIXEL_ROWS,
                    help="re-place x on the scan row the label is defined against "
                         "(recovers the centre row's raster-drift sample; "
                         "see driftsense.matching.drift_row_refine)")
    ap.add_argument("--strip-rotation", dest="strip_rot", action="store_true",
                    default=SHIPPED_STRIP_ROTATION,
                    help="refine rotation from vertical strip offsets and blend it "
                         "with the pose polish (drift-immune; see "
                         "driftsense.matching.strip_rotation)")
    ap.add_argument("--no-strip-rotation", dest="strip_rot", action="store_false",
                    help="force the rotation refinement off regardless of the "
                         "shipped default")
    ap.add_argument("--no-subpixel-rows", dest="subpixel_rows",
                    action="store_false",
                    help="force the row correction off regardless of the shipped default")
    ap.add_argument("--stride", type=int, default=1, help="take every Nth pair")
    ap.add_argument("--sample", type=int, default=0,
                    help="run inference on a deterministic random draw of this many "
                         "pairs instead of the full set -- emulates the organisers' "
                         "200-pair blind grade (use --sample 200)")
    ap.add_argument("--seed", type=int, default=0, help="sample draw seed")
    ap.add_argument("--coarse-scales", type=int, default=17)
    ap.add_argument("--band", action="store_true",
                    help="enable the difference-of-Gaussians band pre-filter "
                         "on the coarse sweep. OFF by default: it mirrors the "
                         "shipped decode (register.py passes band=False; "
                         "measured negative in #18/#24) and is opt-in here for "
                         "A/B use only")
    ap.add_argument("--no-band", action="store_true",
                    help="accepted as a no-op for backward compatibility; band "
                         "is now opt-in via --band (shipped default is OFF)")
    ap.add_argument("--features", action="store_true",
                    help="record rank/band/winner-margin features WITHOUT changing "
                         "the hypothesis selector (the decode stays the shipped zncc "
                         "winner) -- the CSV rejector_cv.py fits on (issue #6)")
    ap.add_argument("--verification", default=SHIPPED_VERIFICATION,
                    choices=["zncc", "consensus", "majority"],
                    help="hypothesis selector implemented in locate_phase2. rank/band/"
                         "dog were measured as research scores and are NOT implemented "
                         "as selectors; the earlier help text advertising them was "
                         "stale and passing them aborted the run")
    ap.add_argument("--denoise", type=int, default=0,
                    help="median filter kernel applied to the search frame (0=off)")
    ap.add_argument("--tie-tol", type=float, default=0.04,
                    help="peaks within this relative margin of the best are "
                         "treated as tied and resolved toward the frame centre")
    ap.add_argument("--early-exit", type=float, default=None,
                    help="stop evaluating pose hypotheses once one verifies at or "
                         "above this native ZNCC. Measured negative: it loses "
                         "points at every setting tried, because the network is "
                         "only 21%% of a pair (issue #7)")
    ap.add_argument("--rescue-margin", type=float, default=None,
                    help="fire a second, denser pose search when the selected "
                         "winner's margin over the runner-up is below this "
                         "(issue #5). Measured negative on the full 2250")
    ap.add_argument("--rescue-delta", type=float, default=0.0,
                    help="a rescued candidate must beat the incumbent by this "
                         "much to be adopted")
    ap.add_argument("--threshold", type=float, default=SHIPPED_THRESHOLD,
                    help="found operating point; mirrors register.py's shipped "
                         "DEFAULT_FOUND_THRESHOLD (driftsense.config) so a "
                         "default run reads the shipped configuration")
    a = ap.parse_args()

    if a.rescore:
        df = pd.read_csv(a.rescore)
    else:
        df = run(a.shards, a.weights, a.jobs, a.threads, a.limit,
                 a.hypotheses, not a.no_polish, not a.no_polish_scale,
                 a.refit_xy, a.stride, a.coarse_scales, a.band,
                 a.verification, a.denoise, a.tie_tol, a.features,
                 a.sample, a.seed, a.early_exit,
                 a.rescue_margin, a.rescue_delta, a.subpixel_rows,
                 a.strip_rot)
        if a.out:
            df.to_csv(a.out, index=False)
            print(f"wrote {a.out}")
    score(df, a.threshold)


if __name__ == "__main__":
    main()
