#!/usr/bin/env python3
"""Score the shipped system against an *external* Phase 2 dataset.

Why this exists separately from `eval_phase2.py`: that script scores a split
produced by our own generator, so it shares every modelling assumption with the
thing under test. A number measured that way cannot see a domain gap. This
script runs the same rubric against a dataset generated by someone else's
generator, which is the closest available proxy for the blind set.

Two honesty rules are enforced here and are the reason the numbers differ from
`eval_phase2.py`:

* **Rejection F1 is reported at the *shipped fixed* threshold**, the one
  `register.py` will actually use on the blind set. The best-achievable F1 over
  a swept threshold is also printed, but clearly labelled, because choosing the
  threshold after seeing the labels is not a result.
* **Localisation is combined with the published weights** (0.45*A + 0.55*B),
  not pooled, so the degraded set carries the weight the rubric gives it.

Inference is parallel across processes purely for wall-clock; per-pair timings
collected here are therefore NOT valid for the efficiency component. Measure
that separately, single-process at 4 threads, on an idle machine.
"""
from __future__ import annotations

import argparse
import os
import sys
import time

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, HERE)

# Published Phase 2 credit tiers.
LOC_TIERS = ((1.0, 1.00), (2.0, 0.80), (3.0, 0.60), (5.0, 0.40))
SCALE_TIERS = ((0.01, 1.00), (0.02, 0.60), (0.05, 0.30))
ROT_TIERS = ((0.25, 1.00), (0.50, 0.60), (1.00, 0.30))
# Localisation weighting across the two present-pair sets.
W_A, W_B = 0.45, 0.55


def tier(value: float, tiers) -> float:
    for bound, credit in tiers:
        if value <= bound:
            return credit
    return 0.0


def _worker(job):
    """Run one pair. Imports happen inside so each process sets its own threads."""
    shard_dir, row, weights, threads, hypotheses, polish, polish_scale, refit_xy, coarse, band, verification, denoise, tie_tol = job
    import torch
    torch.set_num_threads(threads)
    import cv2
    # OpenCV otherwise spawns a pool per *process*, so N workers oversubscribe
    # the machine N-fold and every per-pair timing becomes meaningless.
    cv2.setNumThreads(threads)
    import infer as I
    from driftsense.matching import locate_phase2

    global _MODEL
    try:
        model, device = _MODEL
    except NameError:
        _MODEL = I.load_model(weights)
        model, device = _MODEL

    ref = I.read_gray(os.path.join(shard_dir, row["reference_path"]))
    sea = I.read_gray(os.path.join(shard_dir, row["search_path"]))
    t0 = time.perf_counter()
    res = locate_phase2(model, ref, sea, device, refine=True,
                        hypotheses=hypotheses, polish=polish,
                        polish_scale=polish_scale, refit_xy=refit_xy,
                        coarse_scales=coarse, band=band,
                        verification=verification, denoise=denoise,
                        tie_tol=tie_tol)
    dt = time.perf_counter() - t0
    return {
        "pair_id": row["pair_id"], "set": row["phase2_set"],
        "severity": row.get("severity_level", -1),
        "architecture": row.get("architecture", ""),
        "gt_found": int(row["found"]),
        "gt_x": row["gt_x_corr"], "gt_y": row["gt_y_corr"],
        "gt_scale": row["magnification"], "gt_rot": row["rotation_deg"],
        "x": res["x"], "y": res["y"],
        "scale": res.get("scale", np.nan), "theta": res.get("theta", np.nan),
        # The column register.py actually writes: min(network score, native
        # ZNCC). Recording the raw network score here instead made every
        # threshold in this harness mean something different from the shipped
        # one, which is a very easy way to report a number nobody can reproduce.
        "score": float(res.get("confidence", res.get("score", np.nan))),
        "net_score": float(res.get("score", np.nan)),
        "zncc": float(res.get("zncc", np.nan)),
        # Recorded so the rejection/calibration decision can be re-tuned
        # offline without paying for inference again. peak_ratio is how
        # contested the network's choice was (runner-up / winner among
        # well-separated peaks); pose_peak is the coarse correlation of the
        # winning pose hypothesis.
        "peak_ratio": float(res.get("peak_ratio", np.nan)),
        "pose_peak": float(res.get("pose_peak", np.nan)),
        # Peak-shape statistics (Bolme et al., MOSSE, CVPR 2010). score and
        # zncc are peak *heights* and peak_ratio is a margin over the runner-up;
        # neither describes the surface the peak sits on, and a confident wrong
        # lock-on is a tall peak on a busy surface. Recorded here so a rejector
        # fitted on training shards can be scored on this set without a second
        # inference pass -- without them the fit could never be validated.
        "psr": float(res.get("psr", np.nan)),
        "apce": float(res.get("apce", np.nan)),
        # Rank/band peak-quality at the winner (issue #6): only present when
        # --verification is not zncc (the features are computed then anyway).
        # Recorded so rejector_cv.py can fit the present/absent decision on
        # inference-time features without a second pass.
        "rank": float(res.get("rank", np.nan)),
        "band": float(res.get("band", np.nan)),
        "n_hyp": int(res.get("n_hypotheses", 0)),
        "secs": dt,
    }


def run(shards, weights, jobs, threads, limit, hypotheses, polish,
        polish_scale, refit_xy, stride, coarse, band, verification, denoise, tie_tol):
    import multiprocessing as mp

    tasks = []
    for d in shards:
        man = pd.read_csv(os.path.join(d, "manifest.csv"))
        if stride > 1:
            man = man.iloc[::stride]
        if limit:
            man = man.head(limit)
        for _, r in man.iterrows():
            tasks.append((d, r.to_dict(), weights, threads, hypotheses, polish,
                          polish_scale, refit_xy, coarse, band, verification, denoise, tie_tol))
    print(f"{len(tasks)} pairs over {len(shards)} shard(s), {jobs} workers", flush=True)

    out, t0 = [], time.perf_counter()
    with mp.Pool(jobs) as pool:
        for i, r in enumerate(pool.imap_unordered(_worker, tasks, chunksize=4), 1):
            out.append(r)
            if i % 100 == 0:
                el = time.perf_counter() - t0
                print(f"  {i}/{len(tasks)}  {el/i:.2f}s/pair wall  eta {(len(tasks)-i)*el/i/60:.1f} min",
                      flush=True)
    return pd.DataFrame(out)


def score(df, threshold, quiet=False):
    df = df.copy()
    df["err"] = np.where(df.gt_found == 1, np.hypot(df.x - df.gt_x, df.y - df.gt_y), np.nan)
    df["pred_found"] = (df.score >= threshold).astype(int)
    df["loc_credit"] = df.err.map(lambda e: tier(e, LOC_TIERS) if np.isfinite(e) else np.nan)
    df["s_err"] = np.abs(df.scale - df.gt_scale) / df.gt_scale
    df["r_err"] = np.abs(df.theta - df.gt_rot)

    gray = df[df["set"].isin(["A", "B", "C"])]
    present = gray[gray.gt_found == 1]

    # ---- Localisation (40 pts), weighted 0.45 A + 0.55 B -------------------
    parts, res = {}, {}
    for s in ("A", "B"):
        p = present[present["set"] == s]
        parts[s] = p.loc_credit.mean() if len(p) else np.nan
    loc = W_A * parts["A"] + W_B * parts["B"]
    res["localisation"] = (loc, 40 * loc)

    # ---- Pose (20 pts), only where localisation earned credit --------------
    ok = present[present.loc_credit > 0]
    sc = ok.s_err.map(lambda v: tier(v, SCALE_TIERS)).mean()
    rc = ok.r_err.map(lambda v: tier(v, ROT_TIERS)).mean()
    res["scale"] = (sc, 10 * sc)
    res["rotation"] = (rc, 10 * rc)

    # ---- Rejection (15 pts): F1 on `found` over all grayscale pairs --------
    # Which class is "positive" is NOT resolved by the source material, and the
    # two readings differ by ~1.7 points, so both are reported.
    #
    #   * The scoring slide's line "never rejecting scores zero here" can only
    #     be true under *reject*-as-positive: on 140 present / 40 absent an
    #     always-found system scores exactly 0.000 that way.
    #   * The briefing call instead said "F1 on the found flag", and a second
    #     slide softened it to "a system that never rejects cannot score well",
    #     both of which read naturally as *present*-as-positive, where the same
    #     always-found system scores 0.875.
    #
    # Reject-positive is therefore treated as the conservative planning number
    # -- it is the one that would hurt if we guessed wrong -- and the lenient
    # figure is printed alongside because it is what the earlier self-reported
    # 0.978 was measuring. Do not quote them as if they were the same metric.
    # The operating point is chosen by scripts/optimize_threshold.py against
    # the *total* rubric, which is what makes this ambiguity survivable: the
    # chosen threshold is near-optimal under either reading.
    def f1_at(t, positive="reject"):
        pf = (gray.score >= t).astype(int)              # 1 = we say "found"
        if positive == "reject":
            tp = int(((pf == 0) & (gray.gt_found == 0)).sum())   # correct reject
            fp = int(((pf == 0) & (gray.gt_found == 1)).sum())   # rejected a real one
            fn = int(((pf == 1) & (gray.gt_found == 0)).sum())   # missed an absent
        else:
            tp = int(((pf == 1) & (gray.gt_found == 1)).sum())
            fp = int(((pf == 1) & (gray.gt_found == 0)).sum())
            fn = int(((pf == 0) & (gray.gt_found == 1)).sum())
        return (2 * tp / (2 * tp + fp + fn) if (2 * tp + fp + fn) else 0.0), tp, fp, fn

    f1, tp, fp, fn = f1_at(threshold)
    f1_lenient = f1_at(threshold, "present")[0]
    res["rejection"] = (f1, 15 * f1)
    best = max(((f1_at(t)[0], t) for t in np.unique(gray.score.values)), default=(0, 0))

    # ---- Calibration (10 pts): AUC of score vs per-pair correctness --------
    correct = np.where(gray.gt_found == 1, (gray.err <= 5).fillna(False), False)
    a, b = gray.score.values[correct], gray.score.values[~correct]
    auc = float((a[:, None] > b[None, :]).mean() + 0.5 * (a[:, None] == b[None, :]).mean()) \
        if len(a) and len(b) else float("nan")
    res["calibration"] = (auc, 10 * auc)

    if quiet:
        return res, df

    print(f"\n{'='*74}\nEXTERNAL TEST SET — {len(df)} pairs "
          f"(A {int((df['set']=='A').sum())}, B {int((df['set']=='B').sum())}, "
          f"C {int((df['set']=='C').sum())}, D {int((df['set']=='D').sum())})\n{'='*74}")
    print(f"{'component':<28}{'metric':>26}{'points':>10}")
    print("-" * 74)
    print(f"{'Localisation (40)':<28}{f'credit {loc:.4f}':>26}{40*loc:>10.2f}")
    for s in ("A", "B"):
        p = present[present["set"] == s]
        print(f"{'   set '+s+f' ({len(p)} pairs)':<28}"
              f"{f'{parts[s]:.4f}  <=5px {100*(p.err<=5).mean():.1f}%  <=1px {100*(p.err<=1).mean():.1f}%':>26}")
        print(f"{'':<28}{f'median {p.err.median():.2f}px':>26}")
    print(f"{'Pose — scale (10)':<28}{f'credit {sc:.4f}  med {100*ok.s_err.median():.2f}%':>26}{10*sc:>10.2f}")
    print(f"{'Pose — rotation (10)':<28}{f'credit {rc:.4f}  med {ok.r_err.median():.3f}deg':>26}{10*rc:>10.2f}")
    print(f"{'Rejection (15)':<28}{f'F1(reject) {f1:.4f} @fix {threshold:.3f}':>26}{15*f1:>10.2f}")
    print(f"{'':<28}{f'correct-rej {tp}  lost-real {fp}  missed-abs {fn}':>26}")
    print(f"{'':<28}{f'[lenient F1(present) {f1_lenient:.4f}]':>26}")
    print(f"{'':<28}{f'[best-possible F1(reject) {best[0]:.4f} @ {best[1]:.4f}]':>26}")
    print(f"{'Calibration (10)':<28}{f'AUC {auc:.4f}':>26}{10*auc:>10.2f}")
    print("-" * 74)
    sub = sum(v[1] for v in res.values())
    print(f"{'SUBTOTAL (85 measurable)':<28}{'':>26}{sub:>10.2f}")
    print(f"{'  + efficiency (5)':<28}{'not measurable in parallel':>26}")
    print(f"{'  + generator/report (10)':<28}{'judged, not self-assessable':>26}")

    if (df["set"] == "D").any():
        d = df[df["set"] == "D"]
        dp = d[d.gt_found == 1]
        dc = dp.loc_credit.mean()
        print(f"\n{'BONUS set D (optical)':<28}{f'credit {dc:.4f}  <=5px {100*(dp.err<=5).mean():.1f}%':>26}")
        print(f"{'':<28}{f'+6 needs D>=0.40 and A-C>=0.50':>26}")
    return res, df


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("shards", nargs="+")
    ap.add_argument("--weights", default=os.path.join(HERE, "weights", "driftsense.pt"))
    ap.add_argument("--out", default=None, help="write per-pair results CSV")
    ap.add_argument("--rescore", default=None, help="skip inference, score this CSV")
    ap.add_argument("--jobs", type=int, default=6)
    ap.add_argument("--threads", type=int, default=4)
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--hypotheses", type=int, default=3)
    ap.add_argument("--no-polish", action="store_true")
    ap.add_argument("--no-polish-scale", action="store_true")
    ap.add_argument("--refit-xy", action="store_true")
    ap.add_argument("--stride", type=int, default=1, help="take every Nth pair")
    ap.add_argument("--coarse-scales", type=int, default=17)
    ap.add_argument("--no-band", action="store_true")
    ap.add_argument("--verification", default="zncc",
                    choices=["zncc", "consensus", "majority"],
                    help="hypothesis selector implemented in locate_phase2. rank/band/"
                         "dog were measured as research scores and are NOT implemented "
                         "as selectors; the earlier help text advertising them was "
                         "stale and passing them aborted the run")
    ap.add_argument("--denoise", type=int, default=0,
                    help="median filter kernel applied to the search frame (0=off)")
    ap.add_argument("--tie-tol", type=float, default=0.04,
                    help="peaks within this relative margin of the best are "
                         "treated as tied and resolved toward the frame centre")
    ap.add_argument("--threshold", type=float, default=0.2018,
                    help="found operating point; aligned with register.py's "
                         "DEFAULT_FOUND_THRESHOLD so a default run reads the shipped "
                         "configuration instead of a stale 0.25")
    a = ap.parse_args()

    if a.rescore:
        df = pd.read_csv(a.rescore)
    else:
        df = run(a.shards, a.weights, a.jobs, a.threads, a.limit,
                 a.hypotheses, not a.no_polish, not a.no_polish_scale,
                 a.refit_xy, a.stride, a.coarse_scales, not a.no_band,
                 a.verification, a.denoise, a.tie_tol)
        if a.out:
            df.to_csv(a.out, index=False)
            print(f"wrote {a.out}")
    score(df, a.threshold)


if __name__ == "__main__":
    main()
